registerCheat(14, `<h3>say or tell?</h3>
<p><b>He said (that) he was busy.</b> · <b>He told me (that) he was busy.</b> (tell + person) · He said to me that…</p>
<p>No quote marks, no question mark. <i>that</i> is optional.</p>
<h3>The tense steps back</h3>
<table><tr><th>said</th><th>reported</th></tr>
<tr><td>am / is / are</td><td>was / were</td></tr>
<tr><td>work(s)</td><td>worked</td></tr>
<tr><td>am working</td><td>was working</td></tr>
<tr><td>worked · have worked</td><td>had worked</td></tr>
<tr><td>will</td><td>would</td></tr>
<tr><td>can · may · must</td><td>could · might · had to</td></tr></table>
<p><b>Words that move:</b> I → he/she · my → his/her · today → that day · tomorrow → the next day · yesterday → the day before · now → then · here → there · this → that · ago → before</p>
<p class="sub">No step back if it's still true or just said: <i>She says she's tired.</i></p>
<h3>Reporting questions: no flipping</h3>
<div class="right">"Where do you live?" → She asked where <b>I lived</b>.</div>
<div class="right">"Are you tired?" → He asked <b>if / whether</b> I was tired.</div>
<h3>Commands and requests</h3>
<div class="right">told / asked <b>+ me + to</b> + verb → She told me to sit. · <b>not to</b> → He asked me not to be late.</div>
<h3>Better verbs</h3>
<p>promised (to / that) · suggested (-ing) · warned (me not to) · refused (to) · admitted (that) · explained (that) · advised (me to)</p>
<h3>Top mistakes</h3>
<div class="wrong">He said me that… · He told that…</div><div class="right">He told me that… · He said that…</div>
<div class="wrong">She asked where did I live.</div><div class="right">She asked where I lived.</div>
<div class="wrong">She said me to sit. · He said he will come.</div><div class="right">She told me to sit. · He said he would come.</div>
<h3>Say it</h3>
<p>Mom said she'd be late. · He asked if I was hungry. · She told me not to go. · The boss said the meeting was tomorrow.</p>`);
