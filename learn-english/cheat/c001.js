registerCheat(1, `<h3>The pattern</h3>
<div class="frame"><span class="who">WHO</span><span class="glue">am / is / are</span><span class="rest">REST</span></div>
<table><tr><th>WHO</th><th>glue</th><th>short</th></tr>
<tr><td><b>I</b></td><td>am</td><td>I'm</td></tr>
<tr><td><b>he / she / it</b>, one person or thing</td><td>is</td><td>he's, she's, it's</td></tr>
<tr><td><b>you / we / they</b>, more than one</td><td>are</td><td>you're, we're, they're</td></tr></table>
<p class="sub">Only "I" gets <i>am</i>. "You" always gets <i>are</i>. Count the WHO: one = is, many = are.</p>
<h3>No and questions</h3>
<div class="right">I'm not tired. &nbsp; She isn't here. &nbsp; They aren't late.</div>
<div class="right">Are you ready? &nbsp; Is she at home? &nbsp; Where are you from?</div>
<p>Swap the glue to the front for a question. Short answer, full form: <b>Yes, I am. &nbsp; No, she isn't.</b> Never "Yes, I'm."</p>
<h3>Remember</h3>
<ul><li>Use am/is/are before <b>feelings, places, descriptions</b>. Not before an action (<i>I agree</i>, not <i>I am agree</i>).</li>
<li>Age: <b>I am 25</b>. (Not <i>I have 25 years</i>.)</li>
<li>No <i>amn't</i>. Say <b>I'm not</b>.</li></ul>
<h3>Top mistakes</h3>
<div class="wrong">She happy.</div><div class="right">She is happy.</div>
<div class="wrong">I is tired. / He are here.</div><div class="right">I am tired. / He is here.</div>
<div class="wrong">Where you are from?</div><div class="right">Where are you from?</div>
<h3>Say it</h3>
<p>I'm tired. · My brother is tall. · The keys are on the table. · We're late. · Are you hungry? · She isn't at work today.</p>`);
