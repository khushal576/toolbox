registerCheat(7, `<h3>The question frame</h3>
<div class="frame"><span class="rest">Wh-word</span><span class="glue">helper</span><span class="who">WHO</span><span class="rest">plain verb …?</span></div>
<p><b>Find the helper, put it first.</b> One helper carries the tense; the verb stays <b>plain</b>.</p>
<table><tr><th>sentence has</th><th>helper</th><th>example</th></tr>
<tr><td>am / is / are</td><td>the glue</td><td>Are you ready?</td></tr>
<tr><td>habit</td><td>do / does</td><td>Where does she work?</td></tr>
<tr><td>past</td><td>did</td><td>What did you eat?</td></tr>
<tr><td>-ing</td><td>am / is / are</td><td>Are you coming?</td></tr>
<tr><td>have + participle</td><td>have / has</td><td>Have you eaten?</td></tr>
<tr><td>will / going to</td><td>will / the glue</td><td>Will it rain? Are you going to come?</td></tr></table>
<h3>Who + verb: no helper</h3>
<div class="right">Who called you? &nbsp; What happened? &nbsp; Who knows?</div>
<p class="sub">Word after <b>who</b> is a verb → no did. Word after who is you/he/she → use did: <i>Who did you call?</i></p>
<h3>Wh words</h3>
<table><tr><td><b>what</b> things</td><td><b>who</b> people</td><td><b>where</b> place</td></tr>
<tr><td><b>when</b> time</td><td><b>why</b> reason</td><td><b>how</b> manner</td></tr>
<tr><td colspan="3"><b>how much</b> (price, uncountable) · <b>how many</b> · <b>how long</b> · <b>how often</b> · <b>how far</b> · <b>how old</b></td></tr></table>
<h3>what or which?</h3>
<p><b>what</b> = open answer. <b>which</b> = choose from a set you know. <i>What time? What kind of…? Which bus goes to the station?</i></p>
<h3>Polite questions: no flip</h3>
<div class="right">Could you tell me where <b>the station is</b>? &nbsp; Do you know where <b>he lives</b>?</div>
<p>Short answers: <b>Yes, I do. &nbsp; No, she doesn't. &nbsp; Yes, he did.</b></p>
<h3>Top mistakes</h3>
<div class="wrong">Where you are going?</div><div class="right">Where are you going?</div>
<div class="wrong">What did you ate? &nbsp; Does she works?</div><div class="right">What did you eat? &nbsp; Does she work?</div>
<div class="wrong">Who did call you?</div><div class="right">Who called you?</div>
<div class="wrong">Do you know where does he live?</div><div class="right">Do you know where he lives?</div>
<h3>Say it</h3>
<p>What do you do? · Where did you go? · How far is it? · Which one do you want? · Could you tell me where the bus stop is?</p>`);
