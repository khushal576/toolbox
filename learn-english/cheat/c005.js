registerCheat(5, `<h3>The pattern</h3>
<div class="frame"><span class="who">WHO</span><span class="glue">have / has</span><span class="rest">past participle</span></div>
<p><b>have</b>: I, you, we, they. <b>has</b>: he, she, it (the S lives in <i>has</i>). Regular verbs: the participle = the past (-ed).</p>
<h3>Three jobs</h3>
<div class="right">Experience: <i>I've been to Goa.</i></div>
<div class="right">Still true: <i>I've lived here for five years.</i></div>
<div class="right">Result now: <i>I've lost my keys.</i></div>
<h3>Participles (the 3rd form)</h3>
<table><tr><td>go → went → <b>gone</b></td><td>be → was/were → <b>been</b></td></tr>
<tr><td>see → saw → <b>seen</b></td><td>do → did → <b>done</b></td></tr>
<tr><td>take → took → <b>taken</b></td><td>write → wrote → <b>written</b></td></tr>
<tr><td>eat → ate → <b>eaten</b></td><td>know → knew → <b>known</b></td></tr>
<tr><td>give → gave → <b>given</b></td><td>speak → spoke → <b>spoken</b></td></tr>
<tr><td>drink → drank → <b>drunk</b></td><td>make, buy, have, say, tell → <b>same as past</b></td></tr></table>
<h3>for / since, and the little words</h3>
<p><b>for</b> + a length: for five years. <b>since</b> + a starting point: since 2020. Question: <b>How long have you lived here?</b></p>
<table><tr><td><b>ever</b></td><td>Have you <b>ever</b> been to Goa?</td></tr>
<tr><td><b>never</b></td><td>I have <b>never</b> tried sushi.</td></tr>
<tr><td><b>already</b></td><td>I have <b>already</b> eaten.</td></tr>
<tr><td><b>yet</b></td><td>I haven't eaten <b>yet</b>. Have you eaten <b>yet</b>?</td></tr>
<tr><td><b>just</b></td><td>I have <b>just</b> arrived.</td></tr></table>
<p><b>been</b> = went and came back. <b>gone</b> = still there. Short answers: <b>Yes, I have. &nbsp; No, she hasn't.</b></p>
<h3>Perfect or past simple?</h3>
<p><b>Finished time named</b> (yesterday, last year, in 2019, ago) → <b>past simple</b>. <b>No time, or time up to now</b> (ever, never, already, yet, for, since, this week) → <b>present perfect</b>.</p>
<h3>Top mistakes</h3>
<div class="wrong">I have seen him yesterday.</div><div class="right">I saw him yesterday.</div>
<div class="wrong">I live here since 2020.</div><div class="right">I have lived here since 2020.</div>
<div class="wrong">She have finished. &nbsp; Have you went?</div><div class="right">She has finished. &nbsp; Have you gone/been?</div>
<h3>Say it</h3>
<p>I've never been to Goa. · She's lived here for ten years. · I haven't finished yet. · Have you ever eaten sushi?</p>`);
