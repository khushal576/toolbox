registerCheat(12, `<h3>Comparing two: -er / more … than</h3>
<table><tr><th>word</th><th>do</th><th>example</th></tr>
<tr><td>short</td><td>+er</td><td>tall → taller, cheap → cheaper</td></tr>
<tr><td>short, vowel + consonant</td><td>double</td><td>big → bigger, hot → hotter</td></tr>
<tr><td>ends in y</td><td>y → ier</td><td>happy → happier</td></tr>
<tr><td>long</td><td>more + word</td><td>more expensive</td></tr>
<tr><td>irregular</td><td>—</td><td>good → better · bad → worse · far → farther/further</td></tr></table>
<p>Then <b>than</b>. Stronger: <b>much / a lot</b> + comparative.</p>
<h3>The top: the -est / the most</h3>
<p>the tallest · the biggest · the happiest · <b>the most</b> expensive · the best · the worst. Use <b>in</b> + group, <b>of</b> + set. <i>one of the best films I have seen.</i></p>
<h3>Equal: as … as</h3>
<p><b>as tall as</b> · <b>not as expensive as</b> · the same as · different from · similar to. <b>less</b> + uncountable, <b>fewer</b> + countable.</p>
<h3>Opinions</h3>
<p>I think · I believe · I feel · In my opinion · To me. Ask: <b>What do you think of…? Do you agree?</b> Say the negative first: <b>I don't think</b> he is right. Add <b>because</b> and a reason.</p>
<h3>Agree / disagree politely</h3>
<table><tr><td>I agree. · Exactly. · You're right.</td><td><b>I see what you mean, but…</b> · I'm not sure I agree. · I'm afraid I don't agree.</td></tr></table>
<h3>Top mistakes</h3>
<div class="wrong">more bigger · more better · taller that me</div><div class="right">bigger · better · taller than me</div>
<div class="wrong">the most tall</div><div class="right">the tallest</div>
<div class="wrong">I think he isn't right.</div><div class="right">I don't think he is right.</div>
<h3>Say it</h3>
<p>This is cheaper than that. · She is the smartest in my class. · It isn't as big as I thought. · In my opinion… · I see what you mean, but…</p>`);
