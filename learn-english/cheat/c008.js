registerCheat(8, `<h3>The pattern</h3>
<div class="frame"><span class="who">WHO</span><span class="glue">modal</span><span class="rest">plain verb</span></div>
<p><b>can · could · should · must · would · may · might</b> (+ will). Same for every WHO: <b>no S, no to, no -ing</b>.</p>
<p>No: <b>can't, couldn't, shouldn't, mustn't</b>. Question: modal first (<b>Can you swim?</b>), no do/does. Short answer: <b>Yes, I can. No, she can't.</b></p>
<h3>What each one does</h3>
<table><tr><th>use</th><th>modal</th><th>example</th></tr>
<tr><td>ability</td><td>can / could (past)</td><td>I can cook. I could swim at five.</td></tr>
<tr><td>permission, request</td><td>can / could / may</td><td>Could I borrow your pen?</td></tr>
<tr><td>advice</td><td>should</td><td>You should rest.</td></tr>
<tr><td>rule, strong</td><td>must / have to</td><td>You must wear a belt. I have to wear a uniform.</td></tr>
<tr><td>polite wants, offers</td><td>would</td><td>I'd like a coffee. Would you like tea?</td></tr>
<tr><td>possibility</td><td>may / might</td><td>It might rain.</td></tr>
<tr><td>I'm sure (evidence)</td><td>must</td><td>He must be tired.</td></tr></table>
<h3>The big trap</h3>
<div class="right"><b>mustn't</b> = forbidden. &nbsp; <b>don't have to</b> = not necessary.</div>
<p>have to: <i>She has to… Do you have to…? I had to… I will have to…</i></p>
<h3>The polite ladder</h3>
<p>Give me water. → Can you…? → <b>Could you … , please?</b> (safe for everyone) → Would you mind …ing? → I was wondering if you could… <br>Refuse politely: <i>I'm afraid I can't.</i></p>
<h3>Top mistakes</h3>
<div class="wrong">I can to swim. &nbsp; She cans swim.</div><div class="right">I can swim. &nbsp; She can swim.</div>
<div class="wrong">Do you can swim?</div><div class="right">Can you swim?</div>
<div class="wrong">You mustn't come tomorrow. (not necessary)</div><div class="right">You don't have to come tomorrow.</div>
<div class="wrong">I must to go.</div><div class="right">I must go. / I have to go.</div>
<h3>Say it</h3>
<p>I can cook. · Could you help me, please? · You should rest. · We have to arrive by nine. · It might rain. · I'd like a glass of water.</p>`);
