registerCheat(3, `<h3>The pattern</h3>
<div class="frame"><span class="who">WHO</span><span class="glue">am / is / are</span><span class="rest">verb + ing</span></div>
<p><b>Use it for:</b> right now, around now, temporary. <i>I'm cooking. She's working from home this week.</i></p>
<p class="sub">Need <b>both</b> halves: glue + -ing. <i>She working</i> and <i>She is work</i> are both wrong.</p>
<h3>Spelling -ing</h3>
<table><tr><th>verb</th><th>do</th><th>example</th></tr>
<tr><td>most</td><td>+ing</td><td>work → working</td></tr>
<tr><td>ends in silent e</td><td>drop e</td><td>make → making</td></tr>
<tr><td>short: consonant+vowel+consonant</td><td>double last letter</td><td>run → running, sit → sitting</td></tr>
<tr><td>ends in ie</td><td>ie → y</td><td>lie → lying</td></tr></table>
<h3>No and questions</h3>
<div class="right">I'm not working. &nbsp; She isn't sleeping. &nbsp; They aren't coming.</div>
<div class="right">Are you working? &nbsp; What are you doing? &nbsp; Where is he going?</div>
<p>No do/does here: the glue is the helper. Short answer: <b>Yes, I am.</b></p>
<h3>Verbs that don't take -ing</h3>
<p>States: <b>know, understand, believe, like, love, hate, want, need, prefer, own</b>. <i>I know the answer.</i> (not <i>I am knowing</i>). <i>Have</i>: owning = <i>I have a car</i>; doing = <i>I'm having lunch</i>.</p>
<h3>Now or always?</h3>
<table><tr><th>simple (habit)</th><th>-ing (now)</th></tr>
<tr><td>always, usually, every day</td><td>now, at the moment, today, this week, Look!</td></tr></table>
<h3>Top mistakes</h3>
<div class="wrong">She working now. &nbsp; I am work now.</div><div class="right">She is working now. &nbsp; I am working now.</div>
<div class="wrong">Do you working?</div><div class="right">Are you working?</div>
<div class="wrong">He is runing.</div><div class="right">He is running.</div>
<h3>Say it</h3>
<p>I'm cooking. · They're playing outside. · It's raining. · Are you coming? · What are you doing?</p>`);
