registerCheat(11, `<h3>The joiners</h3>
<table><tr><th>word</th><th>joins</th><th>example</th></tr>
<tr><td><b>and</b></td><td>adds</td><td>I like tea and coffee.</td></tr>
<tr><td><b>but</b></td><td>contrast</td><td>I like tea, but not coffee.</td></tr>
<tr><td><b>or</b></td><td>choice</td><td>Tea or coffee?</td></tr>
<tr><td><b>so</b></td><td>result</td><td>I was tired, so I left.</td></tr>
<tr><td><b>because</b></td><td>reason</td><td>I left because I was tired.</td></tr>
<tr><td><b>although</b></td><td>surprise</td><td>Although it rained, we went out.</td></tr>
<tr><td><b>if / unless</b></td><td>condition</td><td>If it rains, I'll stay. Unless you hurry, you'll be late.</td></tr></table>
<p>Comma before <b>but / so / or</b> when two full sentences join. <b>because + sentence</b>, <b>because of + noun</b>. <b>despite / in spite of + noun</b>. <b>however</b> starts a new sentence.</p>
<h3>One joiner only</h3>
<div class="wrong">Because I was late, so I ran. &nbsp; Although it rained, but we went.</div>
<div class="right">Because I was late, I ran. &nbsp; Although it rained, we went.</div>
<h3>After if / when / before / after / unless / as soon as</h3>
<p>Use the <b>simple present</b>, not will: <i>If it rains, I'll stay home. I'll call you when I arrive.</i></p>
<h3>Telling things in order</h3>
<p><b>First, … Then / Next, … After that, … Finally, …</b> · before · after · while · as soon as · until</p>
<h3>Top mistakes</h3>
<div class="wrong">If I will have time, I'll help.</div><div class="right">If I have time, I'll help.</div>
<div class="wrong">I didn't go because of I was ill.</div><div class="right">because I was ill / because of my illness</div>
<h3>Say it</h3>
<p>I was tired, so I went to bed. · I stayed home because it was raining. · I like tea, but not coffee. · If it rains, I'll stay home. · First…, then…, finally…</p>`);
