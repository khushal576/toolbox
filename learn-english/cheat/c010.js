registerCheat(10, `<h3>Time: at → on → in</h3>
<table><tr><th>at</th><th>on</th><th>in</th></tr>
<tr><td>clock time, night, noon, the weekend</td><td>days, dates, my birthday, Friday morning</td><td>months, years, seasons, the morning / afternoon / evening</td></tr>
<tr><td>at 5 pm · at night</td><td>on Monday · on 15 August</td><td>in June · in 2020 · in summer</td></tr></table>
<p>No preposition: <b>this, next, last, every, tomorrow, yesterday</b> (next week, every day).</p>
<h3>Place</h3>
<table><tr><td><b>in</b> inside, an area</td><td>in the room, in Delhi, in a car, in the box</td></tr>
<tr><td><b>on</b> a surface, line</td><td>on the table, on the wall, on the bus / train / plane</td></tr>
<tr><td><b>at</b> a point, a place's purpose</td><td>at the station, at home, at work, at the door</td></tr></table>
<h3>Movement</h3>
<p><b>to</b> destination · <b>from</b> start · <b>into / out of</b> a space · <b>get on / off</b> a bus, train, plane · <b>get in / out of</b> a car. <b>arrive in</b> a city, <b>arrive at</b> a place. <b>go home</b> (no to).</p>
<h3>for / since / during / by / until</h3>
<table><tr><td><b>for</b> a length</td><td>for two hours</td></tr>
<tr><td><b>since</b> a start point</td><td>since 2018</td></tr>
<tr><td><b>during</b> + noun</td><td>during the film</td></tr>
<tr><td><b>by</b> a deadline</td><td>finish by Friday</td></tr>
<tr><td><b>until</b> up to a point</td><td>wait until six</td></tr></table>
<h3>Fixed pairs (learn as chunks)</h3>
<p>wait <b>for</b> · listen <b>to</b> · look <b>at</b> · depend <b>on</b> · good <b>at</b> · interested <b>in</b> · afraid <b>of</b> · different <b>from</b> · happy <b>with</b> · married <b>to</b> · pay <b>for</b> · talk <b>about</b> · <b>discuss</b> (nothing)</p>
<h3>Top mistakes</h3>
<div class="wrong">in Monday · at Pune · arrive to</div><div class="right">on Monday · in Pune · arrive at / in</div>
<div class="wrong">I'm waiting you. · discuss about</div><div class="right">I'm waiting for you. · discuss it</div>
<div class="wrong">good in English</div><div class="right">good at English</div>
<h3>Say it</h3>
<p>See you on Monday at five. · I live in Pune. · The keys are on the table. · I've been waiting for two hours. · I'm interested in music.</p>`);
