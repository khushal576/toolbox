registerCheat(13, `<h3>The four ifs: how real is it?</h3>
<table><tr><th>how real</th><th>if part</th><th>main part</th><th>example</th></tr>
<tr><td>fact (zero)</td><td>present</td><td>present</td><td>If you heat ice, it melts.</td></tr>
<tr><td>real possibility (first)</td><td>present</td><td>will + verb</td><td>If it rains, I'll stay home.</td></tr>
<tr><td>imaginary now (second)</td><td>past simple</td><td>would + verb</td><td>If I had time, I'd help you.</td></tr>
<tr><td>imaginary past (third)</td><td>had + participle</td><td>would have + participle</td><td>If I'd studied, I'd have passed.</td></tr></table>
<p><b>One step further from reality = one step back in tense.</b> The past in the second conditional is "distance", not time.</p>
<h3>Remember</h3>
<ul><li><b>No will / would after if</b>.</li>
<li>Advice: <b>If I were you, I would…</b> (<i>were</i> for every WHO; <i>was</i> is casual).</li>
<li>Order can swap, no comma: <i>I'd help you if I had time.</i></li>
<li><b>unless</b> = if not. <b>'d</b> = would or had: read the next word.</li></ul>
<h3>wish</h3>
<p><b>I wish I had a car</b> (now) · <b>I wish I were taller</b> · <b>I wish I could swim</b> · <b>I wish I had told him</b> (past regret) · <b>I wish he would stop</b> (annoyance) · <b>If only…</b></p>
<h3>Top mistakes</h3>
<div class="wrong">If it will rain, I will stay.</div><div class="right">If it rains, I will stay.</div>
<div class="wrong">If I would have time, I would help.</div><div class="right">If I had time, I would help.</div>
<div class="wrong">If I studied, I would have passed.</div><div class="right">If I had studied, I would have passed.</div>
<div class="wrong">I wish I can swim. &nbsp; If I am you…</div><div class="right">I wish I could swim. &nbsp; If I were you…</div>
<h3>Say it</h3>
<p>If you hurry, we'll catch it. · If I won the lottery, I would travel. · If I were you, I'd apologize. · If I had known, I would have told you. · I wish I could swim.</p>`);
