"""
schema-copy/server.py

Serves Schema Copy's page and API: copy a database's STRUCTURE — everything
except the rows — into a new, empty database. Source and target are Vault
connections (never typed here). The DDL is generated by the real
`pg_dump --schema-only`; see engine.py for what is wrapped around it and why.

Endpoints
---------
GET    /                           — the single-page UI
GET    /connections                — Vault connections to pick from (id/name only)
GET    /tools                      — are the bundled pg_dump/psql present? (version)
POST   /discover                   — {conn_id} -> that database's schemas (+ object counts), extensions, server version
GET    /projects                   — all projects (+ last-run headline)
POST   /projects                   — create
GET    /projects/{id}              — project + last run + live run state/log
PUT    /projects/{id}              — edit (409 while a run is active)
DELETE /projects/{id}              — delete project and its saved script (409 while running)
POST   /projects/{id}/{action}     — action = preflight | preview | apply | verify (starts a background run)
POST   /projects/{id}/stop         — stop the active run (a stopped apply is rolled back)
GET    /projects/{id}/status       — poll: run state, log tail, last run
GET    /projects/{id}/script       — download the generated .sql
GET    /projects/{id}/script/preview — the first part of the script as text (for the on-page viewer)
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, Optional

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse, HTMLResponse, PlainTextResponse
from pydantic import BaseModel, Field

try:  # package import when mounted inside the toolbox (schema_copy.*)
    from schema_copy import catalog, engine, pgtools, runner, state_store as store
except ImportError:  # flat import when run standalone from within this folder
    import catalog
    import engine
    import pgtools
    import runner
    import state_store as store

try:
    from core import db_endpoint as connections
except ImportError:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from core import db_endpoint as connections
from core.postgres_conn import scrub_password

store.init_db()

app = FastAPI(title="Schema Copy", description="Copy a database's structure (no data) into a new empty database.")
_UI_PATH = Path(__file__).resolve().parent / "ui" / "index.html"
PREVIEW_BYTES = 300_000


class ProjectBody(BaseModel):
    name: str = Field(min_length=1, max_length=120)
    source_conn_id: str
    target_conn_id: str
    schemas: Optional[list[str]] = None  # None / empty = every user schema
    keep_owner: bool = False
    copy_sequences: bool = False


class DiscoverBody(BaseModel):
    conn_id: str


def _conn_name(conn_id: str) -> str:
    for c in connections.list_vault_connections():
        if c["id"] == conn_id:
            return c["name"]
    raise HTTPException(400, f"Vault connection '{conn_id}' not found — pick one from the list.")


def _require(project_id: str) -> dict[str, Any]:
    p = store.get_project(project_id)
    if p is None:
        raise HTTPException(404, "Project not found.")
    return p


def _describe(conn_id: str, name: Optional[str]) -> str:
    try:
        return connections.describe(connections.resolve(conn_id, name))
    except Exception as exc:  # noqa: BLE001 — a missing entry must not break the page
        return f"(unavailable: {exc})"


def _run_state(project_id: str) -> dict[str, Any]:
    v = runner.view(project_id)
    return {"running": v["running"], "queued": v["queued"], "action": v["kind"], "logs": v["logs"],
            "started_at": v["started_at"], "finished_at": v["finished_at"], "stopping": v["stopping"]}


def _check_body(body: ProjectBody) -> None:
    if body.source_conn_id == body.target_conn_id:
        raise HTTPException(400, "Source and target are the same connection — that would copy a database onto itself.")


@app.get("/", response_class=HTMLResponse)
def index() -> HTMLResponse:
    if not _UI_PATH.exists():
        return HTMLResponse("<h1>Schema Copy UI not built yet</h1>", status_code=503)
    return HTMLResponse(_UI_PATH.read_text(encoding="utf-8"), headers={"Cache-Control": "no-cache"})


@app.get("/connections")
def list_connections() -> dict[str, Any]:
    return {"connections": [{"id": c["id"], "name": c["name"]} for c in connections.list_vault_connections()]}


@app.get("/tools")
def tools() -> dict[str, Any]:
    try:
        return {"ok": True, "pg_dump_major": pgtools.client_major("pg_dump"), "psql_major": pgtools.client_major("psql")}
    except pgtools.PgToolError as exc:
        return {"ok": False, "error": str(exc)}


@app.post("/discover")
def discover(body: DiscoverBody) -> dict[str, Any]:
    try:
        data = connections.resolve(body.conn_id)
        with connections.Endpoint(data, read_only=True, label="source") as ep:
            return {
                "connection": connections.describe(data), "version": catalog.server_info(ep.conn)["text"],
                "schemas": catalog.list_schemas(ep.conn), "extensions": catalog.list_extensions(ep.conn),
            }
    except connections.ConnectionError_ as exc:
        raise HTTPException(400, str(exc)) from exc
    except Exception as exc:  # noqa: BLE001
        raise HTTPException(400, scrub_password(str(exc))) from exc


def _headline(p: dict[str, Any]) -> Optional[dict[str, Any]]:
    lr = p["last_run"]
    return {"action": lr["action"], "status": lr["status"], "applied": lr["applied"], "finished_at": lr["finished_at"]} if lr else None


@app.get("/projects")
def list_projects() -> dict[str, Any]:
    return {"projects": [{**{k: p[k] for k in ("id", "name", "source_conn_name", "target_conn_name", "schemas")},
                          "running": runner.is_running(p["id"]), "last": _headline(p)} for p in store.list_projects()]}


@app.post("/projects")
def create_project(body: ProjectBody) -> dict[str, Any]:
    _check_body(body)
    pid = store.create_project(
        name=body.name, source_conn_id=body.source_conn_id, source_conn_name=_conn_name(body.source_conn_id),
        target_conn_id=body.target_conn_id, target_conn_name=_conn_name(body.target_conn_id),
        schemas=body.schemas, keep_owner=body.keep_owner, copy_sequences=body.copy_sequences,
    )
    return {"id": pid}


@app.get("/projects/{project_id}")
def get_project(project_id: str) -> dict[str, Any]:
    p = _require(project_id)
    return {
        "project": p, "source": _describe(p["source_conn_id"], p["source_conn_name"]),
        "target": _describe(p["target_conn_id"], p["target_conn_name"]),
        "run": _run_state(project_id), "has_script": store.has_script(project_id),
    }


@app.put("/projects/{project_id}")
def update_project(project_id: str, body: ProjectBody) -> dict[str, Any]:
    _require(project_id)
    if runner.is_running(project_id):
        raise HTTPException(409, "A run is active — stop it first.")
    _check_body(body)
    store.update_project(
        project_id, name=body.name, source_conn_id=body.source_conn_id, source_conn_name=_conn_name(body.source_conn_id),
        target_conn_id=body.target_conn_id, target_conn_name=_conn_name(body.target_conn_id),
        schemas=body.schemas, keep_owner=body.keep_owner, copy_sequences=body.copy_sequences,
    )
    return {"ok": True}


@app.delete("/projects/{project_id}")
def delete_project(project_id: str) -> dict[str, Any]:
    _require(project_id)
    if runner.is_running(project_id):
        raise HTTPException(409, "A run is active — stop it first.")
    store.delete_project(project_id)
    return {"ok": True}


@app.post("/projects/{project_id}/stop")
def stop(project_id: str) -> dict[str, Any]:
    _require(project_id)
    return {"stopping": runner.stop(project_id)}


@app.post("/projects/{project_id}/{action}")
def start(project_id: str, action: str) -> dict[str, Any]:
    _require(project_id)
    if action not in runner.ACTIONS:
        raise HTTPException(404, f"Unknown action '{action}'.")
    try:
        runner.start(project_id, action)
    except runner.AlreadyRunning as exc:
        raise HTTPException(409, str(exc)) from exc
    return {"ok": True, "action": action}


@app.get("/projects/{project_id}/status")
def status(project_id: str) -> dict[str, Any]:
    p = _require(project_id)
    return {"run": _run_state(project_id), "last_run": p["last_run"], "has_script": store.has_script(project_id)}


@app.get("/projects/{project_id}/script")
def download_script(project_id: str):
    p = _require(project_id)
    path = store.fetch_script(project_id)
    if path is None:
        raise HTTPException(404, "No script generated yet — run Preview or Apply first.")
    safe = "".join(c if c.isalnum() or c in "-_" else "_" for c in p["name"])[:60] or "schema"
    return FileResponse(path, media_type="application/sql", filename=f"{safe}-structure.sql")


@app.get("/projects/{project_id}/script/preview", response_class=PlainTextResponse)
def preview_script(project_id: str) -> PlainTextResponse:
    _require(project_id)
    path = store.fetch_script(project_id)
    if path is None:
        raise HTTPException(404, "No script generated yet.")
    size = path.stat().st_size
    with open(path, "rb") as f:
        head = f.read(PREVIEW_BYTES).decode("utf-8", errors="replace")
    if size > PREVIEW_BYTES:
        head += f"\n\n-- … preview cut at {PREVIEW_BYTES:,} of {size:,} bytes — download the full script …\n"
    return PlainTextResponse(head)
